// コンパクト記述からリッチなスポットオブジェクトを生成するヘルパー
function createMasterSpot({
  id,
  name,
  reading,
  type,
  denomination,
  address,
  lat,
  lng,
  description,
  calligraphy,
  subText,
  stampText,
  specialTitle,
  specialCalligraphy,
  specialDesc,
  motif
}) {
  const sampleGoshuin = [
    {
      id: `${id}-std`,
      title: `通常御朱印「${calligraphy || name}」`,
      badge: '御朱印あり（通年）',
      fee: type === 'shrine' ? '初穂料 500円目安' : '納経料 500円目安',
      calligraphy: calligraphy || name.slice(0, 4),
      subText: subText || `奉拝 ${name}`,
      stampText: stampText || `${name.slice(0, 4)}印`,
      motif: motif || (type === 'shrine' ? 'torii' : 'lotus'),
      description: `${name}の社務所・寺務所にて授与されている代表的な通常御朱印です。`
    }
  ];

  if (specialTitle) {
    sampleGoshuin.push({
      id: `${id}-sp`,
      title: specialTitle,
      badge: '限定・特別御朱印',
      fee: type === 'shrine' ? '初穂料 800〜1,000円目安' : '納経料 800〜1,000円目安',
      calligraphy: specialCalligraphy || calligraphy || name.slice(0, 4),
      subText: subText || name,
      stampText: stampText || '特別朱印',
      motif: 'moon-wave',
      description: specialDesc || '季節や祭礼・行事に合わせて授与される人気の特別御朱印です。'
    });
  }

  return {
    id,
    name,
    reading,
    type,
    denomination,
    address,
    lat,
    lng,
    description,
    hasGoshuin: true,
    sampleGoshuin
  };
}

